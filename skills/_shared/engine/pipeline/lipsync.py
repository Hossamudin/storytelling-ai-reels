"""Mouth keyframes for a 2D character from the voice itself (any language): loudness per frame -> mouth shape.

Usage:
  python engine/pipeline/lipsync.py <name> --part <part> [--voice assets/voice/<file>.wav] [--fps 30]

Writes <part>/assets/js/lipsync.js:
  window.HF_MOUTH = [[t, "X"], ...]   change points only, GLOBAL seconds; shapes:
     "X" closed (rest) · "A" small/mid open · "O" wide open · "M" lips pressed (short closures between syllables)
The character template (kit templates/character_2d.html) turns these into tl.set() calls, so the mouth is
frame-exact and deterministic. Energy-based lip-sync reads as natural for stylized characters in every language;
for close-up realistic sync use a viseme tool and write the same format.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--part", default="composition")
    ap.add_argument("--voice", default=None, help="wav inside the part (default: the voice cue in cues.json)")
    ap.add_argument("--fps", type=int, default=30)
    ap.add_argument("--offset", type=float, default=0.0, help="global start time of the voice")
    a = ap.parse_args()
    import numpy as np
    part = C.project_path(a.name) / a.part
    voice = a.voice
    if not voice:
        cues = json.loads((part / "cues.json").read_text(encoding="utf-8"))
        vo = next((c for c in cues if c.get("voice")), None)
        if not vo:
            sys.exit("No voice cue in cues.json — pass --voice")
        voice, a.offset = vo["src"], float(vo.get("t", 0))
    src = part / voice
    sr = 16000
    import subprocess
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(src), "-ac", "1", "-ar", str(sr), "-f", "s16le", "-"],
                         capture_output=True).stdout
    x = np.frombuffer(raw, np.int16).astype(np.float32) / 32768.0
    hop = sr // a.fps
    n = len(x) // hop
    rms = np.sqrt(np.array([np.mean(x[i * hop:(i + 1) * hop] ** 2) for i in range(n)]) + 1e-12)
    db = 20 * np.log10(rms)
    speech = db[db > -45]
    if len(speech) == 0:
        sys.exit("Voice looks silent.")
    lo, hi = np.percentile(speech, 20), np.percentile(speech, 90)
    lvl = np.clip((db - lo) / max(1e-6, hi - lo), 0, 1)
    shapes, prev = [], None
    for i, v in enumerate(lvl):
        s = "X" if db[i] < -45 or v < 0.08 else ("O" if v > 0.72 else "A")
        # brief dips inside speech read as consonant closures
        if s == "X" and prev in ("A", "O") and i + 2 < n and lvl[i + 1] > 0.3:
            s = "M"
        shapes.append(s)
        prev = s
    # drop 1-frame flickers
    for i in range(1, n - 1):
        if shapes[i - 1] == shapes[i + 1] != shapes[i] and shapes[i] != "M":
            shapes[i] = shapes[i - 1]
    keys, last = [], None
    for i, s in enumerate(shapes):
        if s != last:
            keys.append([round(a.offset + i / a.fps, 3), s])
            last = s
    out = part / "assets/js/lipsync.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// generated by engine/pipeline/lipsync.py — mouth change points (global seconds)\n"
                   f"window.HF_MOUTH = {json.dumps(keys)};\n", encoding="utf-8")
    print(f"OK: {len(keys)} mouth keys over {n / a.fps:.1f}s -> {out}")
    idx = part / "index.html"
    html = idx.read_text(encoding="utf-8")
    if "assets/js/lipsync.js" not in html:  # must load before the scene scripts read window.HF_MOUTH
        html = html.replace('    <script src="assets/js/gsap.min.js"></script>',
                            '    <script src="assets/js/gsap.min.js"></script>' + "\n" +
                            '    <script src="assets/js/lipsync.js"></script>', 1)
        idx.write_text(html, encoding="utf-8")
        print(f"  lipsync.js linked in {idx.name}")


if __name__ == "__main__":
    main()
